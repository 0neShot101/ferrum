//! Fixed APT, Pacman and RPM identities and origins; configuration only selects entries.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Repository {
    Debian,
    DebianSecurity,
    Ubuntu,
    UbuntuSecurity,
    Kali,
    Parrot,
    Trisquel,
    RaspberryPi,
    ProxmoxPve,
    ProxmoxPbs,
    ArchLinux,
    ChaoticAur,
    UbuntuPorts,
    DockerDebian,
    DockerUbuntu,
    TailscaleDebian,
    TailscaleUbuntu,
    PostgresqlApt,
    GrafanaApt,
    CachyOs,
    ArchLinuxCn,
    EndeavourOs,
    AlmaLinux,
    RockyLinux,
}

impl Repository {
    pub const fn name(self) -> &'static str {
        match self {
            Self::Debian => "debian",
            Self::DebianSecurity => "debian-security",
            Self::Ubuntu => "ubuntu",
            Self::UbuntuSecurity => "ubuntu-security",
            Self::Kali => "kali",
            Self::Parrot => "parrot",
            Self::Trisquel => "trisquel",
            Self::RaspberryPi => "raspberrypi",
            Self::ProxmoxPve => "proxmox-pve",
            Self::ProxmoxPbs => "proxmox-pbs",
            Self::ArchLinux => "archlinux",
            Self::ChaoticAur => "chaotic-aur",
            Self::UbuntuPorts => "ubuntu-ports",
            Self::DockerDebian => "docker-debian",
            Self::DockerUbuntu => "docker-ubuntu",
            Self::TailscaleDebian => "tailscale-debian",
            Self::TailscaleUbuntu => "tailscale-ubuntu",
            Self::PostgresqlApt => "postgresql-apt",
            Self::GrafanaApt => "grafana-apt",
            Self::CachyOs => "cachyos",
            Self::ArchLinuxCn => "archlinuxcn",
            Self::EndeavourOs => "endeavouros",
            Self::AlmaLinux => "almalinux",
            Self::RockyLinux => "rockylinux",
        }
    }

    pub const fn origin(self) -> &'static str {
        match self {
            Self::Debian => "https://deb.debian.org/debian/",
            Self::DebianSecurity => "https://deb.debian.org/debian-security/",
            Self::Ubuntu => "https://archive.ubuntu.com/ubuntu/",
            Self::UbuntuSecurity => "https://security.ubuntu.com/ubuntu/",
            Self::Kali => "https://kali.download/kali/",
            Self::Parrot => "https://deb.parrot.sh/direct/parrot/",
            Self::Trisquel => "https://mirrors.ocf.berkeley.edu/trisquel/",
            Self::RaspberryPi => "https://archive.raspberrypi.com/debian/",
            Self::ProxmoxPve => "https://mirrors.ustc.edu.cn/proxmox/debian/pve/",
            Self::ProxmoxPbs => "https://mirrors.ustc.edu.cn/proxmox/debian/pbs/",
            Self::ArchLinux => "https://geo.mirror.pkgbuild.com/",
            Self::ChaoticAur => "https://builds.garudalinux.org/repos/",
            Self::UbuntuPorts => "https://ports.ubuntu.com/ubuntu-ports/",
            Self::DockerDebian => "https://download.docker.com/linux/debian/",
            Self::DockerUbuntu => "https://download.docker.com/linux/ubuntu/",
            Self::TailscaleDebian => "https://pkgs.tailscale.com/stable/debian/",
            Self::TailscaleUbuntu => "https://pkgs.tailscale.com/stable/ubuntu/",
            Self::PostgresqlApt => "https://apt.postgresql.org/pub/repos/apt/",
            Self::GrafanaApt => "https://apt.grafana.com/",
            Self::CachyOs => "https://mirror.cachyos.org/repo/",
            Self::ArchLinuxCn => "https://mirrors.tuna.tsinghua.edu.cn/",
            Self::EndeavourOs => "https://mirrors.tuna.tsinghua.edu.cn/endeavouros/repo/",
            Self::AlmaLinux => "https://repo.almalinux.org/almalinux/",
            Self::RockyLinux => "https://dl.rockylinux.org/pub/rocky/",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DistributionSuite {
    pub repository: Repository,
    pub suite: &'static str,
}

const fn suite(repository: Repository, suite: &'static str) -> DistributionSuite {
    DistributionSuite { repository, suite }
}

